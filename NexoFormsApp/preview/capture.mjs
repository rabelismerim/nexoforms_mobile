import {chromium} from 'playwright';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root = path.dirname(path.dirname(path.dirname(fileURLToPath(import.meta.url))));
const out = path.join(root, 'docs/screenshots');
fs.mkdirSync(out, {recursive: true});
const browser = await chromium.launch({headless: true});
const page = await browser.newPage({viewport: {width: 416, height: 896}, deviceScaleFactor: 1});
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('dialog', dialog => dialog.accept());
try {
  await page.goto('http://127.0.0.1:4173', {waitUntil: 'networkidle'});
  await page.getByText('Tudo começa aqui.', {exact: true}).waitFor();
  const shot = name => page.screenshot({path: path.join(out, name), animations: 'disabled'});
  await shot('01-abertura.png');
  await page.getByLabel('E-mail', {exact: true}).fill('admin.demo@example.com');
  await page.getByLabel('Senha', {exact: true}).fill('Demonstracao123');
  await page.getByRole('button', {name: 'Entrar', exact: true}).click();
  await page.getByText('Meus questionários', {exact: true}).waitFor();
  await shot('02-administrador.png');
  await page.getByText('Gerenciar', {exact: true}).click();
  await page.getByText('Equipe', {exact: true}).waitFor();
  await shot('03-usuarios.png');
  await page.getByLabel('Título', {exact: true}).fill('Checklist de segurança');
  await page.getByLabel('Enunciado da pergunta', {exact: true}).fill('O equipamento está em boas condições?');
  await page.getByRole('button', {name: 'Adicionar pergunta', exact: true}).click();
  await page.getByText('Novo questionário', {exact: true}).evaluate(node => node.scrollIntoView({block: 'start'}));
  await shot('04-criar-formulario.png');
  await page.getByRole('button', {name: 'Ana Costa', exact: true}).first().click();
  await page.getByRole('button', {name: 'Publicar questionário', exact: true}).evaluate(node => node.scrollIntoView({block: 'end'}));
  await shot('08-atribuir-usuarios.png');
  await page.getByText('Questionários', {exact: true}).click();
  await page.getByRole('button', {name: 'Abrir questionário', exact: true}).first().click();
  await page.getByText('1. As condições do local estão adequadas? *', {exact: true}).waitFor();
  await shot('05-responder.png');
  await page.getByRole('button', {name: 'Sim', exact: true}).click();
  await page.getByRole('button', {name: 'Salvar rascunho', exact: true}).click();
  await page.getByRole('button', {name: 'Revisar conflitos de sincronização', exact: true}).click();
  await page.getByText('Revisar conflito', {exact: true}).waitFor();
  await shot('15-conflitos.png');
  await page.getByRole('button', {name: 'Resolver depois', exact: true}).click();
  await page.getByRole('button', {name: 'Sincronizar', exact: true}).click();
  await page.getByText('Respostas', {exact: true}).click();
  await page.getByText('Respostas recebidas', {exact: true}).waitFor();
  await shot('06-respostas-recebidas.png');
  await page.getByLabel('Ampliar foto 1', {exact: true}).first().click();
  await shot('16-foto-ampliada.png');
  await page.getByRole('button', {name: 'Voltar', exact: true}).click();
  await page.getByText('Perfil', {exact: true}).click();
  await page.getByText('Perfil e acesso', {exact: true}).waitFor();
  await shot('07-perfil-offline.png');
  await page.goto('http://127.0.0.1:4173?profile=member', {waitUntil: 'networkidle'});
  await page.getByLabel('E-mail', {exact: true}).fill('ana.demo@example.com');
  await page.getByLabel('Senha', {exact: true}).fill('Demonstracao123');
  await page.getByRole('button', {name: 'Entrar', exact: true}).click();
  await page.getByText('Inspeção de segurança', {exact: true}).waitFor();
  if (await page.getByText('Gerenciar', {exact: true}).count()) throw new Error('Participant must not have administration controls.');
  await shot('09-usuario-pendentes.png');
  await page.getByRole('button', {name: 'Abrir questionário', exact: true}).first().click();
  await page.getByText('1. Os equipamentos estão em boas condições? *', {exact: true}).waitFor();
  await shot('10-usuario-questionario.png');
  await page.getByRole('button', {name: 'Salvar rascunho', exact: true}).click();
  await page.getByText('Perfil', {exact: true}).click();
  await page.getByText('Perfil e acesso', {exact: true}).waitFor();
  await shot('11-usuario-perfil.png');
  await page.goto('http://127.0.0.1:4173', {waitUntil: 'networkidle'});
  await page.getByRole('button', {name: 'Ajustes do aplicativo', exact: true}).click();
  await page.getByText('Ajustes de conexão', {exact: true}).waitFor();
  await shot('12-ajustes-conexao.png');
  await page.getByRole('button', {name: 'Voltar ao login', exact: true}).click();
  await page.getByRole('button', {name: 'Modo online · usar senha offline', exact: true}).click();
  await page.getByLabel('Senha offline', {exact: true}).waitFor();
  await shot('13-login-offline.png');
  await page.goto('http://127.0.0.1:4173?mode=setup', {waitUntil: 'networkidle'});
  await page.getByLabel('E-mail', {exact: true}).fill('admin.demo@example.com');
  await page.getByLabel('Senha', {exact: true}).fill('Demonstracao123');
  await page.getByRole('button', {name: 'Entrar', exact: true}).click();
  await page.getByLabel('Nome do administrador', {exact: true}).waitFor();
  await page.getByLabel('Nome do administrador', {exact: true}).evaluate(node => node.scrollIntoView({block: 'start'}));
  await shot('14-ativar-espaco.png');
  if (errors.length) throw new Error(errors.join('\n'));
  console.log('Captured 16 interface previews covering both roles and all configured screens.');
} catch (error) {
  console.error('Preview error:', error.message, errors);
  await page.screenshot({path: path.join(root, '.verification/preview-error.png')});
  throw error;
} finally {await browser.close();}
